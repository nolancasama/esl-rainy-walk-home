// Builds src/art-manifest.js: which finished images exist for which placeholder.
// Run after adding files to art/scenes or art/portraits: node art/build-manifest.mjs
//
// Scene ids (e.g. bag-12) are assigned in story order exactly as in
// art/build-prompts.mjs. The manifest is keyed by placeholder description, so a
// placeholder whose description is later edited falls back to its emoji stage
// instead of showing the wrong picture.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { STORY } = await import(pathToFileURL(path.join(root, 'src/story.js')));

const ids = new Map();
const counts = {};
function walk(sceneId, beats) {
  for (const beat of beats) {
    const description = beat.visual?.type === 'placeholder' ? beat.visual.description : null;
    if (description && !ids.has(description)) {
      counts[sceneId] = (counts[sceneId] || 0) + 1;
      ids.set(description, `${sceneId}-${String(counts[sceneId]).padStart(2, '0')}`);
    }
    for (const choice of beat.interaction?.choices || []) walk(sceneId, choice.beats || []);
  }
}
for (const [sceneId, scene] of Object.entries(STORY.scenes)) walk(sceneId, scene.beats);

const scenes = {};
const missing = [];
for (const [description, id] of ids) {
  const file = `art/scenes/${id}.webp`;
  if (fs.existsSync(path.join(root, file))) scenes[description] = file;
  else missing.push(id);
}

const portraits = {};
for (const who of Object.keys(STORY.cast)) {
  const file = `art/portraits/${who}.webp`;
  if (fs.existsSync(path.join(root, file))) portraits[who] = file;
}

const source = `// Generated by art/build-manifest.mjs — do not edit by hand.
// Placeholder description -> finished scene image.
export const SCENE_ART = ${JSON.stringify(scenes, null, 2)};

// Cast id -> portrait image.
export const PORTRAIT_ART = ${JSON.stringify(portraits, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src/art-manifest.js'), source);

const castWithoutArt = Object.keys(STORY.cast).filter((who) => who !== 'narrator' && !portraits[who]);
console.log(`${Object.keys(scenes).length}/${ids.size} scenes have art.`);
if (missing.length) console.log(`Missing scenes: ${missing.join(', ')}`);
if (castWithoutArt.length) console.log(`Missing portraits: ${castWithoutArt.join(', ')}`);
